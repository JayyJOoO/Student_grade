def parse_multi_student_csv(file_stream):
    df_raw = pd.read_csv(file_stream, encoding='latin1', header=None)
    students_data = {}
    current_name = None
    current_course_year = None
    current_rows = []

    for idx, row in df_raw.iterrows():
        val0 = str(row[0]).strip()
        if val0.startswith('Name:'):
            if current_name:
                students_data[current_name] = {
                    'course_year': current_course_year,
                    'df': pd.DataFrame(current_rows)
                }
            current_name = str(row[1]).strip()
            current_course_year = str(row[2]).strip()
            current_rows = []
        elif current_name is not None and val0 != 'Code':
            current_rows.append(row)

    if current_name and current_rows:
        students_data[current_name] = {
            'course_year': current_course_year,
            'df': pd.DataFrame(current_rows)
        }
    return students_data

def generate_report(b):
    output_area.clear_output()
    with output_area:
        try:
            if not file_upload.value:
                # Fallback to local test file
                with open('Constantinopla_Student_Gradesws.csv', 'rb') as f:
                    file_stream = io.BytesIO(f.read())
            else:
                uploaded_file = list(file_upload.value.values())[0] if isinstance(file_upload.value, dict) else file_upload.value[0]
                content = uploaded_file.get('content', b'') if isinstance(uploaded_file, dict) else uploaded_file['content']
                file_stream = io.BytesIO(content)

            students_dict = parse_multi_student_csv(file_stream)
            target_name = name_input.value.strip()

            # Find matching student (case-insensitive partial or exact match)
            matched_key = next((k for k in students_dict.keys() if target_name.lower() in k.lower()), None)

            if not matched_key:
                print(f"Student '{target_name}' not found in CSV. Available students: {list(students_dict.keys())}")
                return

            student_info = students_dict[matched_key]
            df = student_info['df']
            df.columns = ['Code', 'Teacher', 'Units', 'Grades']

            # Extract course & year level
            course_year_str = student_info['course_year']
            if '-' in course_year_str:
                parts = course_year_str.rsplit('-', 1)
                course_val = parts[0]
                year_val = parts[1]
            else:
                course_val = course_year_str
                year_val = '1'

            units_col = 'Units'
            grade_col = 'Grades'

            total_subjects = len(df)
            total_units = 0.0
            simple_avg = 0.0
            gwa = 0.0

            if grade_col in df.columns:
                numeric_grades = pd.to_numeric(df[grade_col], errors='coerce')
                simple_avg = numeric_grades.mean()

                if units_col in df.columns:
                    numeric_units = pd.to_numeric(df[units_col], errors='coerce')
                    total_units = numeric_units.sum()

                    valid_mask = numeric_grades.notna() & numeric_units.notna()
                    if numeric_units[valid_mask].sum() > 0:
                        gwa = (numeric_grades[valid_mask] * numeric_units[valid_mask]).sum() / numeric_units[valid_mask].sum()

            display(HTML(f"""
                <div id="printable-report" class="report-card">
                    <div class="report-header-title">
                        🦊 NDMU STUDENT REPORT CARD 🦊
                    </div>

                    <div class="student-info-grid">
                        <span class="info-label">Student Name:</span>
                        <span class="info-value">{matched_key}</span>
                        <span class="info-label">Course/Program:</span>
                        <span class="info-value">{course_val}</span>
                        <span class="info-label">Year Level:</span>
                        <span class="info-value">{year_val}</span>
                    </div>

                    <div class="section-title">
                        🦊 DETAILED SUBJECT GRADES
                    </div>

                    <div class="cyber-table-wrapper">
                        <div class="cyber-table">
                            {df.to_html(classes='cyber-table', index=False)}
                        </div>
                    </div>

                    <div class="section-title">
                        🦊 GRADE SUMMARY
                    </div>

                    <div class="summary-box">
                        <div class="summary-row">
                            <span>Total Subjects Taken:</span>
                            <b>{total_subjects}</b>
                        </div>
                        <div class="summary-row">
                            <span>Total Units Earned:</span>
                            <b>{total_units:.1f}</b>
                        </div>
                        <div class="summary-row">
                            <span>Simple Average Grade:</span>
                            <b>{simple_avg:.2f}</b>
                        </div>
                        <div class="summary-row gwa-highlight">
                            <span>General Weighted Average (GWA):</span>
                            <b>{gwa:.4f}</b>
                        </div>
                    </div>

                    <button class="print-pdf-btn" onclick="window.print()">🖨️ Print Report to PDF</button>
                </div>
            """))
        except Exception as e:
            print(f"Error generating report: {e}")

generate_button.on_click(generate_report)

